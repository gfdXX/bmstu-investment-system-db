-- Задание 3. SQL-запросы к базе данных инвестиционной компании

-- а) SQL запросы на создание всех таблиц

-- Создание таблицы "Клиент"
CREATE TABLE "Клиент" (
    "ID Клиента" INT PRIMARY KEY,
    "Название предприятия" VARCHAR(255),
    "Вид собственности" VARCHAR(255),
    "Адрес" VARCHAR(255),
    "Телефон" VARCHAR(20)
);

-- Создание таблицы "Инвестиционный проект"
CREATE TABLE "Инвестиционный проект" (
    "ID Проекта" INT PRIMARY KEY,
    "Название проекта" VARCHAR(255),
    "Сумма инвестиций" DECIMAL(15, 2),
    "Дата начала" DATE,
    "Дата завершения" DATE,
    "ID Клиента" INT,
    FOREIGN KEY ("ID Клиента") REFERENCES "Клиент"("ID Клиента")
);

-- Создание таблицы "Ценные бумаги"
CREATE TABLE "Ценные бумаги" (
    "ID Ценной бумаги" INT PRIMARY KEY,
    "Тип ценной бумаги" VARCHAR(255),
    "Дата выпуска" DATE,
    "Дата погашения" DATE,
    "Доходность" DECIMAL(5, 2)
);

-- Создание таблицы "Сведения о проекте"
CREATE TABLE "Сведения о проекте" (
    "ID Проекта" INT,
    "ID Ценной бумаги" INT,
    PRIMARY KEY ("ID Проекта", "ID Ценной бумаги"),
    FOREIGN KEY ("ID Проекта") REFERENCES "Инвестиционный проект"("ID Проекта"),
    FOREIGN KEY ("ID Ценной бумаги") REFERENCES "Ценные бумаги"("ID Ценной бумаги")
);

-- б) SQL запросы на удаление всех таблиц

-- Удаление таблицы "Сведения о проекте"
DROP TABLE IF EXISTS "Сведения о проекте";
-- Удаление таблицы "Ценные бумаги"
DROP TABLE IF EXISTS "Ценные бумаги";
-- Удаление таблицы "Инвестиционный проект"
DROP TABLE IF EXISTS "Инвестиционный проект";
-- Удаление таблицы "Клиент"
DROP TABLE IF EXISTS "Клиент";

-- в) SQL запросы на выборку

-- Запрос с WHERE: Выбор всех проектов для конкретного клиента по его ID.
SELECT "Название проекта", "Сумма инвестиций", "Дата начала", "Дата завершения"
FROM "Инвестиционный проект"
WHERE "ID Клиента" = 1;

-- Запрос с ORDER BY: Выбор всех ценных бумаг с сортировкой по доходности в порядке убывания.
SELECT "Тип ценной бумаги", "Дата выпуска", "Дата погашения", "Доходность"
FROM "Ценные бумаги"
ORDER BY "Доходность" DESC;

-- Запрос с агрегацией данных: Подсчет общей суммы инвестиций для всех проектов.
SELECT SUM("Сумма инвестиций") AS "Общая сумма инвестиций"
FROM "Инвестиционный проект";

-- г) Дополнительные запросы

--Запрос с EXISTS: Выбор всех клиентов, у которых есть хотя бы один инвестиционный проект.
SELECT "Название предприятия", "Вид собственности", "Адрес", "Телефон"
FROM "Клиент"
WHERE EXISTS (
    SELECT 1
    FROM "Инвестиционный проект"
    WHERE "Инвестиционный проект"."ID Клиента" = "Клиент"."ID Клиента"
);

--Запрос с ANY: Выбор всех ценных бумаг с доходностью больше доходности любой ценной бумаги, выпущенной в 2020 году.
SELECT "Тип ценной бумаги", "Дата выпуска", "Доходность"
FROM "Ценные бумаги"
WHERE "Доходность" > ANY (
    SELECT "Доходность"
    FROM "Ценные бумаги"
    WHERE EXTRACT(YEAR FROM "Дата выпуска") = 2020
);

--Запрос с ALL: Выбор всех проектов, инвестиционная сумма которых больше всех проектов, начатых в 2021 году.
SELECT "Название проекта", "Сумма инвестиций", "Дата начала"
FROM "Инвестиционный проект"
WHERE "Сумма инвестиций" > ALL (
    SELECT "Сумма инвестиций"
    FROM "Инвестиционный проект"
    WHERE EXTRACT(YEAR FROM "Дата начала") = 2021
);

--Запрос с GROUP BY и HAVING: Подсчет количества проектов у каждого клиента и выбор только тех клиентов, у которых больше одного проекта.
SELECT "ID Клиента", COUNT("ID Проекта") AS "Количество проектов"
FROM "Инвестиционный проект"
GROUP BY "ID Клиента"
HAVING COUNT("ID Проекта") > 1;

--Запрос с UNION: Выбор всех уникальных клиентов и компаний, связанных с проектами и ценными бумагами (например, чтобы получить список всех участников).
SELECT "ID Клиента" AS "Участник", "Название предприятия" AS "Название"
FROM "Клиент"
UNION
SELECT "ID Клиента" AS "Участник", "Название проекта" AS "Название"
FROM "Инвестиционный проект";

--Запрос с INTERSECT: Выбор всех ценных бумаг, которые одновременно числятся в двух разных проектах (если такая ситуация возможна).
SELECT "ID Ценной бумаги"
FROM "Сведения о проекте"
WHERE "ID Проекта" = 1
INTERSECT
SELECT "ID Ценной бумаги"
FROM "Сведения о проекте"
WHERE "ID Проекта" = 2;

--Запрос с EXCEPT: Выбор всех ценных бумаг, которые не задействованы ни в одном проекте.
SELECT "ID Ценной бумаги", "Тип ценной бумаги"
FROM "Ценные бумаги"
EXCEPT
SELECT "ID Ценной бумаги", "Тип ценной бумаги"
FROM "Сведения о проекте";
